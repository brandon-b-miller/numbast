"""Emit the lowering descriptor the generated dialect is driven by.

This renders data, not code. The generic conversion patterns and the analysis
passes live in a runtime package that ships once
(``Runtime Package`` in the config); what is generated per dialect is the table
that tells them which op maps to which symbol, with which operand types, and
which operands are streams.

Three tables, each answering a question the other two cannot:

``_OPS``
    op -> symbol, operand directions, and LLVM-dialect types. Mechanically
    derived from the header.

``_TYPES``
    dialect type -> lowering token, for the conversion framework's
``TypeConverter``.

``_EFFECTS``
    op -> which stream operand it queues work on or waits for. **Not** derivable
    from a header. It is the human-authored half, and the only input that makes
    a scheduling pass such as redundant-sync elimination possible at all.

Why the types are taken from the ABI
------------------------------------
An operand's LLVM type is computed from the same
:func:`~numbast.backends.tablegen.types.abi_c_type` the shim is generated from,
via :func:`~numbast.backends.tablegen.types.llvm_token`. An ``llvm.call``
whose operand types disagreed with the shim's C signature is a miscompile that
nothing downstream would flag, so the two are derived from one source rather
than kept in step by hand.
"""

from numbast.backends.tablegen.config import TableGenOptions
from numbast.backends.tablegen.function import classify_params, mnemonic_for
from numbast.backends.tablegen.types import (
    _is_pointer,
    _pointee,
    abi_c_type,
    llvm_token,
)

__all__ = ["LoweringRenderer"]

_FILE = '''"""Auto-generated lowering + effects descriptor for the {dialect} dialect.

This file is intentionally tiny \u2014 it's just data tables that drive the generic
lowering and analysis passes shipped in `{runtime}`.
"""

from {runtime}.passes import eliminate_redundant_syncs as _elim_syncs
from {runtime}.conversion import lower_to_llvm_via_conversion as _conv


# (mlir_op_name, c_symbol, [(param_name, direction, llvm_type), ...], ret_lowering)
# ret_lowering is the llvm token for the trailing return result ("i32"/"i64"/
# "ptr"/...), or None if the C function returns void (no return result).
_OPS = [
{ops}
]

# Async-stream effects (Tier 2, from the recipe): op_name -> (effect, operand_idx)
# where effect is "enqueue" (queues async work on that stream operand) or "sync"
# (waits on it). Consumed by scheduling passes such as redundant-sync elimination.
_EFFECTS = {{
{effects}
}}

# Dialect type spelling -> lowering token, for the conversion-framework
# TypeConverter (see lower_to_llvm).
_TYPES = {{
{types}
}}


def lower_to_llvm(module):
    """Rewrite {dialect}.* ops in `module` to LLVM dialect ops via MLIR's real
    dialect-conversion framework (ConversionTarget + TypeConverter + autogenerated
    per-op conversion patterns + the conversion driver), in place. Runs partial
    conversion with materialization-building off; a trailing
    reconcile-unrealized-casts folds the bridge casts. Op-level FFI floor -- keep
    dialect types out of function signatures."""
    _conv(module, _OPS, _TYPES)


def eliminate_redundant_syncs(module):
    """Tier-3 example pass: delete redundant {dialect}.* stream syncs, in place.
    Returns the number of syncs removed."""
    return _elim_syncs(module, _EFFECTS)
'''


class LoweringRenderer:
    """Render ``<dialect>_lowering.py`` for a set of function plans.

    Must be constructed with the *same* mapper the ops renderer used, after it
    has rendered: the mapper accumulates the handle and struct types while
    rendering, and this consumes that registry.
    """

    def __init__(
        self,
        plans,
        config: TableGenOptions,
        *,
        mapper,
        types_renderer,
        records: dict | None = None,
        enums=(),
        typedefs=None,
    ):
        self._plans = list(plans)
        self._cfg = config
        self._mapper = mapper
        self._types = types_renderer
        self._records = records or {}
        self._enums = enums or ()
        self._typedefs = typedefs

    # -- helpers ----------------------------------------------------------

    def _abi(self, spelling: str) -> str:
        # by_value_aggregates is not passed: a by-value aggregate operand means
        # the op is excluded from this table anyway, and recording it here would
        # make the shim's POD list depend on the order the renderers ran.
        return abi_c_type(spelling, enums=self._enums, records=self._records)

    def _token(self, spelling: str, direction: str) -> str:
        """LLVM token recorded for one parameter.

        For an out-parameter this is the type of the *pointee* -- the slot the
        lowering allocas and loads back -- not the pointer that is passed. The
        generic lowering re-derives the pointer for the call signature, so
        recording the pointer here would lose the slot's width.
        """
        if direction == "out" and _is_pointer(spelling):
            return llvm_token(self._abi(_pointee(spelling)))
        return llvm_token(self._abi(spelling))

    def _aggregate_type_refs(self) -> set:
        """Dialect type refs that denote a modelled struct or union."""
        prefix = self._cfg.cpp_class_prefix
        return {
            f"{prefix}_{record}Type" for record in self._mapper.structs.values()
        }

    def _op_type_refs(self, decl) -> set:
        """Every dialect type ref this op's signature mentions."""
        refs = set()
        for _param, ptype, direction in classify_params(
            decl, self._mapper, self._cfg.out_param_policy
        ):
            spelling = ptype.unqualified_non_ref_type_name
            if direction == "out":
                refs.add(self._mapper.map_pointee(spelling))
            else:
                refs.add(self._mapper.map(spelling))
        refs.add(
            self._mapper.map(
                decl.return_type.unqualified_non_ref_type_name.strip()
            )
        )
        return refs

    def _mnemonic(self, plan) -> str:
        return self._cfg.mnemonic_overrides.get(
            plan.exposed_name, mnemonic_for(plan.exposed_name)
        )

    def _operand_index(self, decl, param_name: str):
        """Index of ``param_name`` among the op's *operands*.

        Counts only inputs that mapped to a type, because that is exactly what
        the ops renderer emits. Keying the config by parameter name and
        resolving it here is what keeps the effects table correct when a
        parameter's direction is reclassified.
        """
        index = 0
        for param, ptype, direction in classify_params(
            decl, self._mapper, self._cfg.out_param_policy
        ):
            if direction != "in":
                continue
            if not self._mapper.map(ptype.unqualified_non_ref_type_name):
                continue
            if param.name == param_name:
                return index
            index += 1
        return None

    # -- tables -----------------------------------------------------------

    def _included_plans(self):
        """Plans that the generic table can lower.

        An op carrying a modelled aggregate is excluded: lowering it means also
        lowering the struct.undef/insert/extract chain and materialising the
        value to memory for the by-pointer call, which the current conversion
        patterns do not do. Excluding it is what keeps the table honest -- a row
        here is a claim that the generic pattern handles the op.
        """
        aggregates = self._aggregate_type_refs()
        for plan in self._plans:
            if not plan.c_symbol:
                continue  # lowered by a hand-written pass, not this table
            if self._op_type_refs(plan.decl) & aggregates:
                continue
            yield plan

    def _ops_table(self) -> str:
        rows = []
        for plan in self._included_plans():
            decl = plan.decl
            params = ", ".join(
                f'("{param.name}", "{direction}", '
                f'"{self._token(ptype.unqualified_non_ref_type_name, direction)}")'
                for param, ptype, direction in classify_params(
                    decl, self._mapper, self._cfg.out_param_policy
                )
            )
            ret_abi = self._abi(
                decl.return_type.unqualified_non_ref_type_name.strip()
            )
            ret = repr(llvm_token(ret_abi)) if ret_abi != "void" else "None"
            rows.append(
                f'    ("{self._cfg.dialect_name}.{self._mnemonic(plan)}", '
                f'"{plan.c_symbol}", [{params}], {ret}),'
            )
        return "\n".join(rows)

    def _effects_table(self) -> str:
        """Resolve ``Stream Effects`` onto operand indices."""
        by_name = {p.exposed_name: p for p in self._plans}
        rows = []
        for exposed_name, (effect, param_name) in sorted(
            self._cfg.stream_effects.items()
        ):
            plan = by_name.get(exposed_name)
            if plan is None:
                raise ValueError(
                    f"Stream Effects names {exposed_name!r}, which is not an "
                    f"exposed function. Check the name against "
                    f"'API Prefix Removal'."
                )
            index = self._operand_index(plan.decl, param_name)
            if index is None:
                raise ValueError(
                    f"Stream Effects[{exposed_name}] names parameter "
                    f"{param_name!r}, which is not an operand of that op."
                )
            rows.append(
                f'    "{self._cfg.dialect_name}.{self._mnemonic(plan)}": '
                f'("{effect}", {index}),'
            )
        return "\n".join(rows)

    def _types_table(self) -> str:
        """Dialect type -> lowering token.

        Built from the types renderer's own mnemonic list rather than recomputed,
        so a type the ops reference cannot be missing from the converter.
        Aggregates are dropped: every op that mentions one is excluded from
        ``_OPS``, so those types never reach a converted module.
        """
        aggregates = {
            record.lower() for record in self._mapper.structs.values()
        }
        rows = []
        for mnemonic in self._types.mnemonics():
            if mnemonic in aggregates:
                continue
            token = "i32" if mnemonic == "result" else "ptr"
            rows.append(
                f'    "!{self._cfg.dialect_name}.{mnemonic}": "{token}",'
            )
        return "\n".join(rows)

    def render_as_str(self) -> str:
        runtime = self._cfg.runtime_package
        if not runtime:
            raise ValueError(
                "Runtime Package is required to emit the lowering descriptor: "
                "the generated file imports the generic passes from it."
            )
        return _FILE.format(
            dialect=self._cfg.dialect_name,
            runtime=runtime,
            ops=self._ops_table(),
            effects=self._effects_table(),
            types=self._types_table(),
        )
